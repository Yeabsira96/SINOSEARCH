# Lazy pinyin (tone-mark diacritics) for pronunciation help.
# ---------------------------------------------------------------------------
_PINYIN: dict[str, str] = {}


def _load_pinyin() -> bool:
    global _PINYIN
    try:
        from pypinyin import Style, lazy_pinyin  # type: ignore
        def _py(s: str) -> str:
            return " ".join(lazy_pinyin(s, style=Style.TONE))
        _PINYIN_fn = _py
        globals()["_PY_FN"] = _py
        return True
    except Exception:
        return False


_HAS_PINYIN = None
_PY_FN = None


def romanize(text: str) -> str:
    """Return space-separated tone pinyin for CJK chars ('' if unavailable)."""
    global _HAS_PINYIN
    if _HAS_PINYIN is None:
        _HAS_PINYIN = _load_pinyin()
    if not _HAS_PINYIN or not text:
        return ""
    runs = _CJK_RUN.findall(text)
    if not runs:
        return ""
    return " ".join(_PY_FN(r) for r in runs[:2])
