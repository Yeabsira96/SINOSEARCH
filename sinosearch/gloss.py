# merge curated terms into char map fallbacks lazily (terms win at segment level)
TERMS = dict(_TERMS_RAW)
CHAR = dict(_CHAR_GLOSS)

# longest-first term list for greedy segmentation
_SORTED_TERMS = sorted(TERMS.keys(), key=len, reverse=True)


def _segment_run(run: str) -> list[str]:
    """Greedy longest-match segmentation of a CJK run using TERMS then CHAR."""
    segs: list[str] = []
    i, n = 0, len(run)
    while i < n:
        matched = None
        if n - i >= 2:
            for t in _SORTED_TERMS:
                if len(t) >= 2 and run.startswith(t, i):
                    matched = t
                    break
        if matched:
            segs.append(matched)
            i += len(matched)
        else:
            segs.append(run[i])
            i += 1
    return segs


def annotate(text: str) -> list[tuple[str, str | None]]:
    """Split text into [(segment, english_or_None)]; non-CJK segments get None."""
    out: list[tuple[str, str | None]] = []
    pos = 0
    for m in _CJK_RUN.finditer(text):
        if m.start() > pos:
            out.append((text[pos:m.start()], None))
        for seg in _segment_run(m.group(0)):
            en = TERMS.get(seg) or CHAR.get(seg)
            out.append((seg, en))
        pos = m.end()
    if pos < len(text):
        out.append((text[pos:], None))
    return out


def gloss_sentence(text: str, max_chars: int = 200) -> str:
    """Inline bilingual expansion: 上海[Shanghai] 落户[settle one's ...]."""
    clipped = text[:max_chars]
    parts = []
    for seg, en in annotate(clipped):
        if en:
            parts.append(f"{seg}[{en}]")
        else:
            parts.append(seg)
    s = "".join(parts)
    return s + ("…" if len(text) > max_chars else "")


def literal_en(text: str, max_chars: int = 200) -> str:
    """Pure English literal rendering of Chinese text (offline best-effort)."""
    clipped = text[:max_chars]
    parts = []
    for seg, en in annotate(clipped):
        parts.append(en if en else seg)
    s = " ".join(p.strip() for p in parts if p.strip())
    s = re.sub(r"\s+", " ", s)
    return s + ("…" if len(text) > max_chars else "")


